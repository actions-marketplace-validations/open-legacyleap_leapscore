/**
 * Generate `lib/generated/samples.ts` from the committed envelope directory
 * (design D4/D6). The directory is the manifest: the generated module wires
 * each file name to a static JSON import, so adding a sample file is the whole
 * edit. It also emits `SAMPLE_ROW_INDEX` — every indicator a committed envelope
 * carries, with the sample slug and report anchor — so an indicator document can
 * link to the evidence that exercised it without a request-time filesystem read.
 *
 * Runs as the package `prebuild` step and can be run by hand:
 *
 *   ./node_modules/.bin/tsx scripts/build-samples-manifest.ts
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(import.meta.dirname, "..");

/** One committed document, keyed by its file name. */
export type SampleDocument = { fileName: string; document: unknown };

type SampleRow = { id?: string; status?: string; score?: number | null };

/** The rows a committed envelope exposes through `report.full_table`. */
export function sampleRows(document: unknown): SampleRow[] {
  const report = (document as { report?: { full_table?: unknown } } | null)?.report;
  const rows = report?.full_table;
  return Array.isArray(rows) ? (rows as SampleRow[]) : [];
}

/**
 * The indicator → evidence index. Keyed by indicator ID, ordered by file name,
 * then by the row order inside each envelope. An ID with no committed row is
 * simply absent — the browser never fabricates an evidence link.
 */
export function sampleRowIndex(
  documents: readonly SampleDocument[],
): Record<string, Array<{ slug: string; anchor: string }>> {
  const index = new Map<string, Array<{ slug: string; anchor: string }>>();
  for (const { fileName, document } of [...documents].sort((a, b) =>
    a.fileName.localeCompare(b.fileName),
  )) {
    const slug = fileName.replace(/\.json$/, "");
    for (const row of sampleRows(document)) {
      if (!row.id) continue;
      const entries = index.get(row.id) ?? [];
      entries.push({ slug, anchor: `row-${row.id}` });
      index.set(row.id, entries);
    }
  }
  return Object.fromEntries([...index.entries()].sort(([a], [b]) => a.localeCompare(b)));
}

/** Build the generated module's source for a list of sample file names and documents. */
export function samplesManifestSource(
  fileNames: readonly string[],
  documents: readonly SampleDocument[] = [],
): string {
  const files = [...fileNames].sort();
  const imports = files
    .map(
      (fileName, index) =>
        `import sample${index} from "../samples/${fileName}";`,
    )
    .join("\n");
  const entries = files
    .map(
      (fileName, index) =>
        `  { fileName: ${JSON.stringify(fileName)}, document: sample${index} },`,
    )
    .join("\n");
  const indexEntries = Object.entries(sampleRowIndex(documents))
    .map(([id, rows]) => `  ${JSON.stringify(id)}: ${JSON.stringify(rows)},`)
    .join("\n");

  return `// Generated by scripts/build-samples-manifest.ts — do not hand-edit.
// The committed envelopes in lib/samples/ are the source; adding a file and
// rebuilding is the only step needed to list and serve a new sample.
${imports}

export const SAMPLE_FILES = [
${entries}
] as const;

export type SampleRowLink = { slug: string; anchor: string };

// Every indicator a committed envelope carries, with the sample slug and the
// report anchor that renders it. Absence is honest: no link is fabricated.
export const SAMPLE_ROW_INDEX: Record<string, SampleRowLink[]> = {
${indexEntries}
};
`;
}

function main(): void {
  const samplesDir = join(SITE, "lib", "samples");
  const files = readdirSync(samplesDir)
    .filter((fileName) => fileName.endsWith(".json"))
    .sort();
  const documents: SampleDocument[] = files.map((fileName) => ({
    fileName,
    document: JSON.parse(readFileSync(join(samplesDir, fileName), "utf-8")),
  }));

  const generatedDir = join(SITE, "lib", "generated");
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(
    join(generatedDir, "samples.ts"),
    samplesManifestSource(files, documents),
  );
  console.log(
    `samples-manifest: wrote lib/generated/samples.ts (${files.length} sample file(s), ${Object.keys(sampleRowIndex(documents)).length} indicator row(s))`,
  );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
