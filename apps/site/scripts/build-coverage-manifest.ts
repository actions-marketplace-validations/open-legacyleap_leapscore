/**
 * Generate `lib/generated/coverage.ts` from the shipped detector tree (design D5).
 *
 * The detector tree is the source: one file per implemented indicator, named
 * `<code><NN>.ts` (`arch01.ts` → `ARCH-01`). The engine version comes from
 * `apps/scanner/package.json`, so the published coverage sentence moves with the
 * release instead of being hand-typed in a page. A missing tree, an unparseable
 * file name, or a duplicate ID fails the build loudly.
 *
 *   ./node_modules/.bin/tsx scripts/build-coverage-manifest.ts
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(import.meta.dirname, "..");
const DEFAULT_DETECTORS = join(SITE, "..", "scanner", "src", "scan", "detectors");
const DEFAULT_SCANNER_PACKAGE = join(SITE, "..", "scanner", "package.json");
const DEFAULT_RUBRIC_JSON = join(
  SITE,
  "..",
  "scanner",
  "src",
  "scan",
  "scoring",
  "rubric.json",
);

/** A detector file is `<lowercase code><two-digit number>.ts`; `common.ts` carries no indicator. */
const DETECTOR_FILE = /^([a-z]+)(\d{2})\.ts$/;

/** Map detector file names to indicator IDs, ignoring the shared helper module. */
export function mapDetectorFiles(fileNames: readonly string[]): string[] {
  const ids = new Set<string>();
  for (const fileName of [...fileNames].sort()) {
    if (!fileName.endsWith(".ts")) continue;
    if (fileName === "common.ts") continue;
    const match = fileName.match(DETECTOR_FILE);
    if (!match) {
      throw new Error(
        `detector file ${fileName} is not <code><NN>.ts — cannot map it to an indicator ID`,
      );
    }
    const id = `${match[1].toUpperCase()}-${match[2]}`;
    if (ids.has(id)) throw new Error(`duplicate detector for ${id}`);
    ids.add(id);
  }
  return [...ids].sort();
}

/** The generated module's source for a detector set, engine version, and denominator. */
export function coverageManifestSource(
  indicatorIds: readonly string[],
  engineVersion: string,
  total: number,
): string {
  const ids = [...indicatorIds].sort();
  const entries = ids.map((id) => `  ${JSON.stringify(id)},`).join("\n");
  return `// Generated by scripts/build-coverage-manifest.ts — do not hand-edit.
// The shipped detector tree (apps/scanner/src/scan/detectors/<code><NN>.ts) is the
// source; the engine version is read from apps/scanner/package.json.
export const COVERAGE_ENGINE_VERSION = ${JSON.stringify(engineVersion)};
export const COVERAGE_TOTAL = ${total};
export const COVERAGE_INDICATOR_IDS = [
${entries}
] as const;

export function isIndicatorImplemented(id: string): boolean {
  return (COVERAGE_INDICATOR_IDS as readonly string[]).includes(id);
}
`;
}

/** Read the detector tree and engine version, and return the generated source. */
export function buildCoverageManifest(
  detectorsDir = DEFAULT_DETECTORS,
  scannerPackage = DEFAULT_SCANNER_PACKAGE,
  rubricJson = DEFAULT_RUBRIC_JSON,
): string {
  if (!existsSync(detectorsDir)) {
    throw new Error(
      `detector directory ${detectorsDir} is missing — the coverage manifest cannot be derived`,
    );
  }
  const ids = mapDetectorFiles(readdirSync(detectorsDir));
  if (ids.length === 0) {
    throw new Error(`detector directory ${detectorsDir} yielded zero indicators`);
  }

  const engineVersion = JSON.parse(readFileSync(scannerPackage, "utf-8")).version;
  if (typeof engineVersion !== "string" || !engineVersion) {
    throw new Error(`${scannerPackage} carries no engine version`);
  }

  const rubric = JSON.parse(readFileSync(rubricJson, "utf-8")) as {
    indicators?: unknown[];
  };
  const total = rubric.indicators?.length ?? 0;
  if (!total) throw new Error(`${rubricJson} carries no indicator rows`);

  for (const id of ids) {
    if (!(rubric.indicators ?? []).some((row) => (row as { id?: string }).id === id)) {
      throw new Error(`detector ${id} has no row in the compiled rubric`);
    }
  }

  return coverageManifestSource(ids, engineVersion, total);
}

function main(): void {
  const source = buildCoverageManifest();
  const generatedDir = join(SITE, "lib", "generated");
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(join(generatedDir, "coverage.ts"), source);
  const ids = mapDetectorFiles(readdirSync(DEFAULT_DETECTORS));
  console.log(
    `coverage-manifest: wrote lib/generated/coverage.ts (${ids.length} detector(s))`,
  );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
